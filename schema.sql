-- 1. Admins Table
CREATE TABLE IF NOT EXISTS admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Sections Table (Categorized into 'main' sections and 'bills' sections)
CREATE TABLE IF NOT EXISTS sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    panel TEXT DEFAULT 'main' NOT NULL
);

-- 3. Subsections Table
CREATE TABLE IF NOT EXISTS subsections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id BIGINT NOT NULL REFERENCES sections(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    CONSTRAINT unique_section_subsection UNIQUE(section_id, name)
);

-- 4. Documents Table (PDF metadata, section, subsection, file_url & file_path in bucket 'pdfs')
CREATE TABLE IF NOT EXISTS documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT DEFAULT '',
    section TEXT DEFAULT '',
    subsection TEXT DEFAULT '',
    section_id BIGINT REFERENCES sections(id) ON DELETE CASCADE,
    subsection_id BIGINT REFERENCES subsections(id) ON DELETE CASCADE,
    file_url TEXT NOT NULL,
    file_path TEXT NOT NULL,
    file_size BIGINT DEFAULT 0,
    uploaded_at TIMESTAMPTZ DEFAULT NOW()
);

-- Safe migrations in case table already exists with older schema
ALTER TABLE documents ADD COLUMN IF NOT EXISTS section TEXT DEFAULT '';
ALTER TABLE documents ADD COLUMN IF NOT EXISTS subsection TEXT DEFAULT '';
ALTER TABLE documents ADD COLUMN IF NOT EXISTS file_url TEXT DEFAULT '';
ALTER TABLE documents ADD COLUMN IF NOT EXISTS file_path TEXT DEFAULT '';
ALTER TABLE documents ADD COLUMN IF NOT EXISTS file_size BIGINT DEFAULT 0;

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_sections_panel ON sections(panel);
CREATE INDEX IF NOT EXISTS idx_subsections_section_id ON subsections(section_id);
CREATE INDEX IF NOT EXISTS idx_documents_subsection_id ON documents(subsection_id);
CREATE INDEX IF NOT EXISTS idx_documents_section_id ON documents(section_id);
CREATE INDEX IF NOT EXISTS idx_documents_uploaded_at ON documents(uploaded_at DESC);

-- 5. Supabase Storage Bucket Setup ('pdfs' bucket with public access for fast PDF preview & download)
INSERT INTO storage.buckets (id, name, public)
VALUES ('pdfs', 'pdfs', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Storage Policy: Allow public read access to 'pdfs' bucket
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE tablename = 'objects' 
        AND schemaname = 'storage' 
        AND policyname = 'Public Access PDFs'
    ) THEN
        CREATE POLICY "Public Access PDFs" 
        ON storage.objects FOR SELECT 
        USING (bucket_id = 'pdfs');
    END IF;
END $$;

-- Storage Policy: Allow all operations with service role / authenticated
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE tablename = 'objects' 
        AND schemaname = 'storage' 
        AND policyname = 'Allow PDF Uploads'
    ) THEN
        CREATE POLICY "Allow PDF Uploads" 
        ON storage.objects FOR ALL 
        USING (bucket_id = 'pdfs')
        WITH CHECK (bucket_id = 'pdfs');
    END IF;
END $$;

